assert.ok(!context.$plugins.some(p=>p.name==='Dryland_Presentation'));
context.$plugins.push({name:'Dryland_Presentation',status:true,description:'Integração de apresentação nativa',parameters:{}});
fs.writeFileSync(root+'js/plugins.js','// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n'+context.$plugins.map(p=>JSON.stringify(p)).join(',\n')+'\n];\n');
fs.writeFileSync(root+'data/CommonEvents.json','[\n'+events.map(e=>JSON.stringify(e)).join(',\n')+'\n]\n');
for(const [name,value] of [['Map003.json',map],['Map002.json',prologue]])fs.writeFileSync(root+'data/'+name,JSON.stringify(value,null,2)+'\n');
console.log(JSON.stringify({roleIds,prologue:units}));
